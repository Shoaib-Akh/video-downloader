// Helper to update cookies.txt
async function updateCookiesFile() {
  try {
    const cookies = await session.defaultSession.cookies.get({ domain: '.youtube.com' })

    if (!cookies.length) {
      console.error('No YouTube cookies found.')
      return
    }

    // Build a header line recognized by yt-dlp.
    const lines = [
      '# Netscape HTTP Cookie File',
      '# This file is generated by Electron for use by yt-dlp.',
      '# This file was last updated on ' + new Date().toString(),
      '' // blank line after header
    ]

    // Convert each cookie to a proper Netscape line
    // Fields (tab-separated):
    // domain, include_subdomains, path, secure, expiration, name, value
    cookies.forEach((cookie) => {
      // Example: If the domain is "youtube.com" and you want to cover subdomains, prefix it with a dot.
      // But if it's already something like ".youtube.com", leave it.
      let domain = cookie.domain
      if (!domain.startsWith('.')) {
        // In many official examples, you only do this if you want subdomains = TRUE
        domain = '.' + domain
      }

      // Force "TRUE" if we want subdomains. If you only want EXACT domain matching, use "FALSE".
      const includeSubdomains = 'TRUE'

      // Some cookies from YouTube might be secure, some not. Typically you can do:
      const isSecure = cookie.secure ? 'TRUE' : 'FALSE'

      // expiry (seconds) or 0 if session cookie
      const expiry = cookie.expirationDate ? Math.floor(cookie.expirationDate) : 0

      // Construct the line
      // Typically these fields are tab-separated. Some tools are okay with spaces, but
      // `yt-dlp` is most consistent if you use a single tab between fields.
      const line = [
        domain,
        includeSubdomains,
        cookie.path,
        isSecure,
        expiry,
        cookie.name,
        cookie.value
      ].join('\t')

      lines.push(line)
    })

    // Join all lines with \n
    const fileContent = lines.join('\n')

    writeFileSync(cookiesPath, fileContent, 'utf8')
    console.log('Cookies updated successfully at:', cookiesPath)
  } catch (error) {
    console.error('Error updating cookies:', error)
  }
}

function createWindow() {
  const mainWindow = new BrowserWindow({
    width: 900,
    height: 670,
    show: false,
    autoHideMenuBar: true,
    ...(process.platform === 'linux' ? { icon } : {}),
    webPreferences: {
      webviewTag: false,
      nativeWindowOpen: true,
      nodeIntegration: true, // or false, depending on your needs
      preload: join(__dirname, '../preload/index.js'),
      sandbox: false
    }
  })

  mainWindow.on('ready-to-show', () => {
    mainWindow.show()
  })

  mainWindow.webContents.setWindowOpenHandler((details) => {
    shell.openExternal(details.url)
    return { action: 'deny' }
  })

  if (is.dev && process.env['ELECTRON_RENDERER_URL']) {
    mainWindow.loadURL(process.env['ELECTRON_RENDERER_URL'])
  } else {
    mainWindow.loadFile(join(__dirname, '../renderer/index.html'))
  }
}

