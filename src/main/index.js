// Retrieve original filename
// Using spawn + parse stdout
// -------------------------------------
function getFilename(url) {
  return new Promise((resolve, reject) => {
    const args = ['--get-filename', '-o', '%(title)s', url]
    const proc = spawn(ytdlpPath, args)

    let stdout = ''
    let stderr = ''

    proc.stdout.on('data', (data) => {
      stdout += data.toString()
    })

    proc.stderr.on('data', (data) => {
      stderr += data.toString()
    })

    proc.on('close', (code) => {
      if (code === 0) {
        resolve(stdout.trim())
      } else {
        reject(new Error(`getFilename failed: ${stderr}`))
      }
    })
  })
}

// -------------------------------------
// Download with progress
// Pass in either video/audio format + path
// -------------------------------------
function downloadWithProgress(event, url, format, outputPath, stage) {
  return new Promise((resolve, reject) => {
    // Example: yt-dlp -f <format> -o <path> <url>
    const args = ['-f', format, '-o', outputPath, url, '--newline', '--progress']
    const proc = spawn(ytdlpPath, args)

    proc.stdout.on('data', (data) => {
      const line = data.toString().trim()
      // Optional: parse progress lines from yt-dlp
      // They often look like:
      // [download]   0.2% of 3.05MiB at 402.74KiB/s ETA 00:07

      // A quick regex to capture relevant data:
      const regex = /\[download\]\s+([\d.]+)% of ([\d.]+\w+) at\s+([\d.]+\w+\/s)\s+ETA\s+([\d:]+)/

      if (regex.test(line)) {
        const match = line.match(regex)
        if (match) {
          const progress = parseFloat(match[1]) || 0
          const fileSize = match[2] || ''
          const speed = match[3] || ''
          const eta = match[4] || ''

          event.sender.send('download-progress', {
            progress,
            fileSize,
            speed,
            eta,
            status: `${stage} downloading...`,
            file: outputPath
          })
        }
      }
    })

    proc.stderr.on('data', (data) => {
      console.error(`yt-dlp ${stage} stderr:`, data.toString())
    })

    proc.on('close', (code) => {
      if (code === 0) {
        resolve()
      } else {
        reject(new Error(`yt-dlp ${stage} download failed with code ${code}`))
      }
    })
  })
}

// -------------------------------------
// Merge with ffmpeg & send optional progress
// -------------------------------------
function mergeVideoAudio(event, videoPath, audioPath, outputPath) {
  return new Promise((resolve, reject) => {
    ffmpegFluent()
      .input(videoPath)
      .input(audioPath)
      .outputOptions('-c:v copy')
      .outputOptions('-c:a aac')
      .outputOptions('-strict experimental')
      .on('progress', (info) => {
        // FFmpeg progress is different from yt-dlp's.
        // You only get an approximate "frames" or "time" object
        // You can compute approximate percentage if you know total duration.
        // For simplicity, we’ll just send a “merging in progress” message:
        event.sender.send('download-progress', {
          progress: 99, // or keep it separate from the main progress
          fileSize: '',
          speed: '',
          eta: '',
          status: `Merging...`,
          file: outputPath
        })
      })
      .on('end', () => {
        resolve(outputPath)
      })
      .on('error', (err) => {
        reject(`Merge error: ${err.message}`)
      })
      .save(outputPath)
  })
}

function safeUnlink(path) {
  try {
    if (existsSync(path)) {
      unlinkSync(path)
    }
  } catch (e) {
    console.warn(`Failed to remove temp file: ${path}`, e)
  }
}

