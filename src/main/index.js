// Open a webview for YouTube
// -------------------------------------
ipcMain.on('open-webview', (event, url) => {
  let webviewWindow = new BrowserWindow({
    height: 600,
    webPreferences: {
      webviewTag: true,
      nodeIntegration: false,
      contextIsolation: true
    }
  })

  webviewWindow.loadURL(url)

  // 1) For full navigations:
  webviewWindow.webContents.on('did-navigate', async (e, navigationUrl) => {
    if (navigationUrl.includes('youtube.com')) {
      await updateCookiesFile()
    }
  })

  // 2) For in-page navigations (like clicking a new video without a full reload)
  webviewWindow.webContents.on('did-navigate-in-page', async (e, navigationUrl) => {
    if (navigationUrl.includes('youtube.com')) {
      await updateCookiesFile()
    }
  })

  webviewWindow.on('closed', () => {
    webviewWindow = null
  })
})

