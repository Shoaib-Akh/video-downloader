// -------------------------------------
// Dynamically fetch formats via yt-dlp -F
// -------------------------------------
ipcMain.handle('getFormats', async (event, url) => {
  return new Promise((resolve, reject) => {
    const args = ['-F', url]
    const proc = spawn(ytdlpPath, args)

    let stdout = ''
    let stderr = ''

    proc.stdout.on('data', (data) => {
      stdout += data.toString()
    })

    proc.stderr.on('data', (data) => {
      stderr += data.toString()
    })

    proc.on('close', (code) => {
      if (code !== 0) {
        console.error('Error fetching formats:', stderr)
        return reject("Failed to fetch formats")
      } else {
        const formats = parseFormats(stdout)
        resolve(formats)
      }
    })
  })
})

// Only return the lines that match a typical "ID EXT RES/bitrate" pattern
function parseFormats(output) {
  return output
    .split('\n')
    .map((line) => {
      // Example lines from "yt-dlp -F"
      // 18 mp4  640x360
      // 22 mp4  1280x720
      // 140 m4a audio only
      const match = line.match(/^(\d+)\s+(\w+)\s+(\S+)/)
      if (!match) return null

      const formatId = match[1]
      const formatType = match[2]
      const quality = match[3] // could be resolution or "audio only"

      return { formatId, formatType, quality }
    })
    .filter(Boolean)
}
