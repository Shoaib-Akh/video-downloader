// Open a webview for YouTube
// -------------------------------------
ipcMain.on('open-webview', (event, url) => {
  let webviewWindow = new BrowserWindow({
    height: 600,
    webPreferences: {
      webviewTag: true,
      nodeIntegration: false,
      contextIsolation: true
    }
  })

  webviewWindow.loadURL(url)

  // 1) For full navigations:
  webviewWindow.webContents.on('did-navigate', async (e, navigationUrl) => {
    if (navigationUrl.includes('youtube.com')) {
      await updateCookiesFile()
    }
  })

  // 2) For in-page navigations
  webviewWindow.webContents.on('did-navigate-in-page', async (e, navigationUrl) => {
    if (navigationUrl.includes('youtube.com')) {
      await updateCookiesFile()
    }
  })

  webviewWindow.on('closed', () => {
    webviewWindow = null
  })
})

// -------------------------------------
// Download video with yt-dlp + progress
// -------------------------------------
ipcMain.handle('downloadVideo', async (event, options) => {
  try {
    const { url, isAudioOnly, selectedFormat, selectedQuality } = options

    // Decide on a download folder
    const downloadDir = app.getPath('downloads')
    if (!existsSync(downloadDir)) {
      mkdirSync(downloadDir, { recursive: true })
    }

    // Provide a fallback if selectedQuality is undefined
    const finalQuality = selectedQuality || '720'
    const finalFormat = selectedFormat?.toLowerCase() || 'mp4'

    // 1) Build the format specifier:
    let formatSpecifier
    if (isAudioOnly) {
      // Example: force MP3, highest quality
      // or use user’s chosen format + quality
      formatSpecifier = `--extract-audio --audio-format ${finalFormat} --audio-quality ${finalQuality}`
    } else {
      // Example: -f "mp4[height<=720]+bestaudio" or fallback to best
      formatSpecifier = `-f ${finalFormat}[height<=${finalQuality}]+bestaudio/${finalFormat}+bestaudio/best`
    }

    // 2) Output template 
    //    Using a combination of flags to sanitize file names.
    const outputTemplate = `${downloadDir}/%(title)s.%(ext)s`

    // 3) Build the spawn arguments
    const args = [
      ...formatSpecifier.split(' '),
      '--ffmpeg-location', ffmpegPath,
      '--cookies', cookiesPath, 
      '--embed-metadata',
      '--embed-thumbnail',
      '--restrict-filenames',
      '--windows-filenames',
      '-o', outputTemplate,
      url,
      '--newline',        // So we can parse progress line by line
      '--ignore-errors',
      '--no-warnings',
      '--ignore-config',
      '--no-simulate',
      '--quiet',
      '--progress',
      '--print', 'title',      // optional
      '--print', 'thumbnail'   // optional
      // '--no-playlist',      // if you want to avoid playlist downloads
    ]

    // 4) Actually spawn yt-dlp
    const proc = spawn(ytdlpPath, args)

    return await new Promise((resolve, reject) => {
      let stdoutData = ''
      let stderrData = ''

      proc.stdout.on('data', (data) => {
        const line = data.toString().trim()
        stdoutData += line + '\n'

        // Simple regex to parse progress lines like:
        // [download]   0.2% of 3.05MiB at 402.74KiB/s ETA 00:07
        const regex = /\[download\]\s+([\d.]+)% of ([\d.]+\w+) at\s+([\d.]+\w+\/s)\s+ETA\s+([\d:]+)/

        const match = line.match(regex)
        if (match) {
          const progress = parseFloat(match[1]) || 0
          const fileSize = match[2] || ''
          const speed = match[3] || ''
          const eta = match[4] || ''

          // Send progress to renderer
          event.sender.send('download-progress', {
            progress,
            fileSize,
            speed,
            eta,
            status: isAudioOnly ? 'Downloading audio...' : 'Downloading video...',
            file: outputTemplate
          })
        }
      })

      proc.stderr.on('data', (data) => {
        const line = data.toString().trim()
        stderrData += line + '\n'
        console.error('[yt-dlp stderr]', line)
      })

      proc.on('close', (code) => {
        if (code === 0) {
          // Possibly send a final 100% event
          event.sender.send('download-progress', {
            progress: 100,
            fileSize: '',
            speed: '',
            eta: '',
            status: 'Download complete!',
            file: outputTemplate
          })
          resolve(outputTemplate)
        } else {
          reject(new Error(`yt-dlp exited with code ${code}.\n${stderrData}`))
        }
      })
    })
  } catch (err) {
    console.error('downloadVideo error:', err)
    throw err
  }
})

